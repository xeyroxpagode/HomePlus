DECISION_DIRECT_RESPONSE = "direct_response"

DECISION_TOOL_REQUEST = "tool_request"

DECISION_CLARIFY = "clarify"

DECISION_VALUES: tuple[str, ...] = (
    DECISION_DIRECT_RESPONSE,
    DECISION_TOOL_REQUEST,
    DECISION_CLARIFY,
)

DECISION_FIELDS: tuple[str, ...] = (
    "decision",
    "answer",
    "question",
    "tool_id",
    "arguments",
)

# Fields that are trusted orchestration metadata and must never be produced
# by the model.
MODEL_FORBIDDEN_FIELDS: tuple[str, ...] = (
    "tool_call_id",
    "catalog_digest",
    "request_id",
    "trace_id",
    "actor_id",
    "household_id",
    "authorization",
)


class ToolDecisionError(ValueError):
    """Fail-closed error raised when a model decision is not valid."""

    def __init__(
        self,
        code: str,
        message: str,
    ) -> None:

        super().__init__(
            f"{code}: {message}"
        )

        self.code = code
        self.message = message


def _is_plain_json_object(
    value: Any,
) -> bool:
    """Whether a value is a plain JSON object."""

    if not isinstance(value, dict):
        return False

    for key, item in value.items():
        if not isinstance(key, str):
            return False

        if not _is_json_value(item):
            return False

    return True


def _is_json_value(
    value: Any,
) -> bool:
    """Whether a value is JSON compatible."""

    if value is None or isinstance(value, str):
        return True

    if isinstance(value, bool):
        return True

    if isinstance(value, int):
        return True

    if isinstance(value, float):
        return (
            value == value
            and value not in (
                float("inf"),
                float("-inf"),
            )
        )

    if isinstance(value, list):
        return all(
            _is_json_value(item) for item in value
        )

    if isinstance(value, dict):
        return all(
            isinstance(key, str) and _is_json_value(item)
            for key, item in value.items()
        )

    return False


class ToolDecisionV1(BaseModel):
    """The T09-internal model decision contract, version 1.

    All five fields are required. Extra fields are forbidden. The three
    decision shapes are mutually exclusive; the combination is checked by a
    deterministic post-validator, never by coercion.
    """

    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
    )

    decision: Literal[
        "direct_response",
        "tool_request",
        "clarify",
    ]
    answer: str | None
    question: str | None
    tool_id: str | None
    arguments: dict[str, Any] | None

    @model_validator(mode="before")
    @classmethod
    def _check_raw_payload(
        cls,
        value: Any,
    ) -> Any:
        """Reject malformed payloads before any coercion happens."""

        if not isinstance(value, dict):
            raise ValueError(
                "the decision payload must be a JSON object"
            )

        for field in MODEL_FORBIDDEN_FIELDS:
            if field in value:
                raise ValueError(
                    f"{field!r} is trusted orchestration metadata and "
                    "must not be generated by the model"
                )

        arguments = value.get("arguments")

        if arguments is not None:
            if not _is_plain_json_object(arguments):
                raise ValueError(
                    "'arguments' must be a plain JSON object"
                )

            forbidden = forbidden_keys_in_arguments(arguments)

            if forbidden:
                raise ValueError(
                    "'arguments' must not carry identity/auth/transport "
                    "fields: " + ", ".join(forbidden)
                )

        return value

    @model_validator(mode="after")
    def _check_mutual_exclusivity(self) -> "ToolDecisionV1":
        """Enforce the three mutually exclusive decision shapes."""

        if self.decision == DECISION_DIRECT_RESPONSE:
            if not (
                isinstance(self.answer, str)
                and self.answer.strip()
            ):
                raise ValueError(
                    "direct_response requires a non-empty 'answer'"
                )

            if (
                self.question is not None
                or self.tool_id is not None
                or self.arguments is not None
            ):
                raise ValueError(
                    "direct_response requires 'question', 'tool_id' and "
                    "'arguments' to be null"
                )

            return self

        if self.decision == DECISION_CLARIFY:
            if not (
                isinstance(self.question, str)
                and self.question.strip()
            ):
                raise ValueError(
                    "clarify requires a non-empty 'question'"
                )

            if (
                self.answer is not None
                or self.tool_id is not None
                or self.arguments is not None
            ):
                raise ValueError(
                    "clarify requires 'answer', 'tool_id' and 'arguments' "
                    "to be null"
                )

            return self

        # tool_request
        allowed_tool_ids = set(effective_tool_ids())

        if self.tool_id not in allowed_tool_ids:
            raise ValueError(
                "tool_request requires a canonical tool_id, got "
                f"{self.tool_id!r}"
            )

        if not isinstance(self.arguments, dict):
            raise ValueError(
                "tool_request requires 'arguments' to be a plain JSON object"
            )

        if (
            self.answer is not None
            or self.question is not None
        ):
            raise ValueError(
                "tool_request requires 'answer' and 'question' to be null"
            )

        return self


def parse_decision(
    payload: Any,
) -> ToolDecisionV1:
    """Validate a raw model decision payload.

    Invalid output is never coerced into a valid decision: the payload is
    either accepted as-is or rejected.
    """

    try:
        return ToolDecisionV1.model_validate(payload)
    except ValidationError as error:
        raise ToolDecisionError(
            "TOOL_DECISION_INVALID",
            _describe_validation_error(error),
        ) from error


def _describe_validation_error(
    error: ValidationError,
) -> str:
    parts: list[str] = []

    for item in error.errors():
        location = ".".join(
            str(entry) for entry in item["loc"]
        )

        parts.append(
            f"{location or '<root>'}: {item['msg']}"
        )

    return "; ".join(parts)


def decision_json_schema() -> dict[str, Any]:
    """The deterministic JSON Schema of the model decision contract.

    The schema is intentionally flat: no ``oneOf``, no ``allOf``, no
    ``$ref``. The mutual exclusivity of the three decision shapes is
    enforced by the post-validator, not by the schema.
    """

    return {
        "type": "object",
        "additionalProperties": False,
        "required": list(DECISION_FIELDS),
        "properties": {
            "decision": {
                "type": "string",
                "enum": list(DECISION_VALUES),
            },
            "answer": {
                "type": ["string", "null"],
            },
            "question": {
                "type": ["string", "null"],
            },
            "tool_id": {
                "type": ["string", "null"],
                "enum": [
                    *effective_tool_ids(),
                    None,
                ],
            },
            "arguments": {
                "type": ["object", "null"],
            },
        },
    }


def decision_json_schema_text() -> str:
    """The deterministic JSON text of the decision JSON Schema."""

    return json.dumps(
        decision_json_schema(),
        indent=2,
        sort_keys=True,
        ensure_ascii=False,
    ) + "\n"


def _check_primitive(
    name: str,
    value: Any,
    schema: Mapping[str, Any],
) -> list[str]:
    """Deterministic primitive checks for a single argument."""

    violations: list[str] = []

    declared_type = schema.get("type")

    if declared_type is not None:
        types = (
            declared_type
            if isinstance(declared_type, list)
            else [declared_type]
        )

        matched = False

        for candidate in types:
            if candidate == "string" and isinstance(value, str):
                matched = True
            elif candidate == "boolean" and isinstance(
                value, bool
            ):
                matched = True
            elif candidate == "integer" and (
                isinstance(value, int)
                and not isinstance(value, bool)
            ):
                matched = True
            elif candidate == "number" and (
                isinstance(value, (int, float))
                and not isinstance(value, bool)
            ):
                matched = True
            elif candidate == "null" and value is None:
                matched = True
            elif candidate == "object" and isinstance(
                value, dict
            ):
                matched = True
            elif candidate == "array" and isinstance(
                value, list
            ):
                matched = True

        if not matched:
            violations.append(
                f"invalid_type:{name}"
            )

            return violations

    enum_values = schema.get("enum")

    if (
        isinstance(enum_values, list)
        and value not in enum_values
    ):
        violations.append(f"not_in_enum:{name}")

    minimum = schema.get("minimum")

    if (
        isinstance(minimum, (int, float))
        and not isinstance(minimum, bool)
        and isinstance(value, (int, float))
        and not isinstance(value, bool)
        and value < minimum
    ):
        violations.append(f"below_minimum:{name}")

    maximum = schema.get("maximum")

    if (
        isinstance(maximum, (int, float))
        and not isinstance(maximum, bool)
        and isinstance(value, (int, float))
        and not isinstance(value, bool)
        and value > maximum
    ):
        violations.append(f"above_maximum:{name}")

    min_length = schema.get("minLength")

    if (
        isinstance(min_length, int)
        and not isinstance(min_length, bool)
        and isinstance(value, str)
        and len(value) < min_length
    ):
        violations.append(f"too_short:{name}")

    pattern = schema.get("pattern")

    if (
        isinstance(pattern, str)
        and isinstance(value, str)
        and re.search(pattern, value) is None
    ):
        violations.append(f"pattern_mismatch:{name}")

    return violations


def precheck_tool_arguments(
    tool_id: str,
    arguments: Any,
) -> list[str]:
    """Deterministic argument precheck for a tool request.

    T09-B is *not* a full JSON Schema validator and does not implement a
    second copy of the T07 argument validator. T07 remains the final
    argument authority; this precheck only performs the cheap, reusable
    checks:

    * the tool exists in the catalogue;
    * the arguments are a plain JSON object;
    * no identity/auth/URL key is present;
    * no unknown top-level argument name against the tool input schema;
    * every required argument name is present;
    * the small primitive constraints that the simple T07 schemas express
      (type, enum, minimum, maximum, minLength, pattern).

    The returned list is empty when the precheck passes and is otherwise a
    deterministic list of violation codes.
    """

    violations: list[str] = []

    loaded = None
    loaded_v2 = None

    try:
        loaded = catalog()
    except ToolCatalogError:
        loaded = None

    definition = loaded.get(tool_id) if loaded is not None else None

    if definition is None and is_t24_read_enabled():
        try:
            loaded_v2 = catalog_v2()
        except ToolCatalogError:
            loaded_v2 = None

        definition = (
            loaded_v2.get(tool_id) if loaded_v2 is not None else None
        )

        if definition is None and loaded_v2 is not None:
            return ["unknown_tool"]
    elif definition is None:
        return ["unknown_tool"]

    if loaded is None and loaded_v2 is None:
        return [f"catalog_unavailable"]

    if not _is_plain_json_object(arguments):
        return ["arguments_not_object"]

    forbidden = forbidden_keys_in_arguments(arguments)

    for key in forbidden:
        violations.append(f"forbidden_key:{key}")

    schema = definition["inputSchema"]

    properties = schema.get("properties", {})

    for name in sorted(arguments):
        if name not in properties:
            violations.append(f"unknown_argument:{name}")

    for name in schema.get("required", []):
        if name not in arguments:
            violations.append(f"missing_required:{name}")

    for name in sorted(arguments):
        if name not in properties:
            continue

        violations.extend(
            _check_primitive(
                name,
                arguments[name],
                properties[name],
            )
        )

    return violations


def assert_tool_arguments(
    tool_id: str,
    arguments: Any,
) -> None:
    """Fail closed when the argument precheck reports a violation."""

    violations = precheck_tool_arguments(
        tool_id,
        arguments,
    )

    if violations:
        raise ToolDecisionError(
            "TOOL_ARGUMENTS_INVALID",
            f"{tool_id}: " + ", ".join(violations),
        )
