"""HOMI T09-B — internal T09 decision contract V1 (Node D).

This is a T09-INTERNAL contract. It is deliberately separate from the frozen
T05 contract package:

* it does not live in ``C:\\Homi\\contracts``;
* it does not touch ``homi_contracts``;
* it does not touch ``schemas``;
* it does not touch ``contract_version``.

The contract describes the logical decision that the model is asked to make
and nothing else. It carries no execution metadata: ``tool_call_id``,
``catalog_digest``, ``request_id``, ``trace_id``, ``actor_id``,
``household_id`` and ``authorization`` are trusted orchestration metadata
minted by Node D, never by the model.

The module is inert: no HTTP, no HomePlus authentication, no tool execution,
no model call.
"""

