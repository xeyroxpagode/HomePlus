// Genera backend/src/homi/v1/generatedBindings.js desde 04_TOOL_CATALOG_FINAL.json.
// Binding estático por tool_id (sin requires dinámicos, sin endpoint eligido por el modelo).
const fs = require('fs');
const path = require('path');
const D = __dirname;
const finalCatalog = JSON.parse(fs.readFileSync(path.join(D, '04_TOOL_CATALOG_FINAL.json'), 'utf8'));

const all = finalCatalog.tools;
// Registro a partir de esta pasada: solo tools objetivo tienen binding ejecutable.
const target = finalCatalog.tools.filter((t) => t.read_write === 'READ' || t.read_write === 'WRITE');
const binding = {
  schema_version: '1.0.0',
  generated_at: new Date().toISOString(),
  pass: '2/2 implementation',
  policy: 'Registro estático: cada binding apunta al endpoint canónico congelado del catálogo. No se puede invocar endpoint arbitrario.',
  targets: target.map((t) => ({
    tool_id: t.tool_id,
    domain: t.domain,
    risk_class: t.risk_class,
    read_write: t.read_write,
    http: t.http,
    canonical_service: t.canonical_service,
    required_capabilities: t.required_capabilities || [],
    household_scope: t.household_scope,
    confirmation_policy: t.confirmation_policy,
    execution_handler: t.execution.handler,
    idempotency_policy: t.execution.idempotency,
    ledger: t.execution.ledger,
    audit_events: t.audit_events || ['homi.tool.execution.started', 'homi.tool.execution.read'],
  })),
  count: { total: all.length, target: target.length, read: target.filter(t => t.read_write==='READ').length, write: target.filter(t => t.read_write==='WRITE').length },
};
const outPath = path.resolve(path.join(D, '..', '..', '..', '..', 'backend', 'src', 'homi', 'v1', 'generatedBindings.js'));
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `'use strict';

// @generated by docs/homi/full-integration/closure-discovery/_gen_runtime_bindings.cjs
// Do not edit by hand. Regenerate from 04_TOOL_CATALOG_FINAL.json.

const BINDINGS = ${JSON.stringify(binding, null, 2)};

function getBinding(toolId) {
  if (typeof toolId !== 'string') return null;
  return BINDINGS.targets.find((t) => t.tool_id === toolId) || null;
}

function listBindings() {
  return BINDINGS.targets;
}

module.exports = { BINDINGS, getBinding, listBindings };
`);
console.log('generatedBindings.js written:', outPath, 'tools:', binding.count.target);
