# Genera homi_write_schemas.py (módulo del orquestador D) desde homi-tools.v2.json (307 tools).
# Salida: homi_orchestrator/homi_write_schemas.py con WRITE_CONTRACTS + validate_arguments.
import json
import re
from pathlib import Path

D = Path(__file__).resolve().parent
CAT = D / ".." / ".." / ".." / ".." / "homi-orchestrator" / "catalog" / "homi-tools.v2.json"
OUT = D / ".." / ".." / ".." / ".." / "homi-orchestrator" / "homi_write_schemas.py"

CAT = CAT.resolve()
OUT = OUT.resolve()

doc = json.loads(CAT.read_text(encoding="utf-8"))
tools = doc["tools"]
write_tools = [t for t in tools if t["kind"] == "WRITE"]

# Configuración de riesgo por Tool Contract (19 families + específicas).
MODERATE_PATTERNS = re.compile(
    r"(trash|cancel|delete|permanent|archive|unarchive|close|fail|correct|"
    r"settle|settle|remove|unassign|adjust|terminate|revoke|expire|stop|hold|block|restart|reopen|reject|restore|finalize)",
    re.IGNORECASE,
)
# Aplicar MODERATE a tools por su id (más conservador: las acciones destructivas o de autoridad humana).
MODERATE_IDS = set()
for t in tools:
    if MODERATE_PATTERNS.search(t["tool_id"]) or t["tool_id"] in {
        "finance.pools.release",
        "finance.pools.transfer",
        "messages.messages.send",
        "inventory.products.permanent-delete",
    }:
        MODERATE_IDS.add(t["tool_id"])

contracts = {}
for t in write_tools:
    tid = t["tool_id"]
    contracts[tid] = {
        "kind": "WRITE",
        "risk_flags": ("MODERATE_MUTATION",) if tid in MODERATE_IDS else ("LOW_MUTATION",),
        "confirmation": "REQUIRED",
        "contract_version": "2.0.0",
        "input_schema": t["inputSchema"],
        "execution_enabled": True,
        "domain_binding": f"/api mapping via binding registry (frozen endpoint in {CAT.name})",
    }

print(f"write contracts: {len(contracts)}; moderate: {len(MODERATE_IDS)}")

lines = []
lines.append("# @generated by docs/homi/full-integration/closure-discovery/_gen_write_schemas.py")
lines.append("# Do not edit by hand. Regenerate from homi-tools.v2.json.")
lines.append("from __future__ import annotations")
lines.append("")
lines.append("from typing import Any, Mapping")
lines.append("")
lines.append("")
lines.append("WRITE_CONTRACTS: dict[str, dict[str, Any]] = {")
for tid in sorted(contracts):
    c = contracts[tid]
    flags = "(" + ", ".join(f'"{f}"' for f in c["risk_flags"]) + ",)"
    lines.append(f"    {tid!r}: {{")
    lines.append(f"        \"kind\": {c['kind']!r},")
    lines.append(f"        \"risk_flags\": {flags},")
    lines.append(f"        \"confirmation\": {c['confirmation']!r},")
    lines.append(f"        \"contract_version\": {c['contract_version']!r},")
    lines.append(f"        \"input_schema\": {repr(c['input_schema'])},")
    lines.append(f"        \"execution_enabled\": {str(c['execution_enabled'])},")
    lines.append(f"        \"domain_binding\": {repr(c['domain_binding'])},")
    lines.append("    },")
lines.append("}")
lines.append("")
lines.append("# Ids con protección del validador genérico.")
lines.append(f"MODERATE_IDS: frozenset[str] = frozenset({sorted(MODERATE_IDS)!r})")
lines.append("")
lines.append("")
lines.append("def _check_primitive(key, value, prop):")
lines.append("    t = prop.get('type')")
lines.append("    if t == 'string' and not isinstance(value, str):")
lines.append("        return f'invalid_type:{key}'")
lines.append("    if t == 'integer' and (not isinstance(value, int) or isinstance(value, bool)):")
lines.append("        return f'invalid_type:{key}'")
lines.append("    if t == 'number' and not isinstance(value, (int, float)) or isinstance(value, bool):")
lines.append("        return f'invalid_type:{key}'")
lines.append("    if t == 'boolean' and not isinstance(value, bool):")
lines.append("        return f'invalid_type:{key}'")
lines.append("    if t == 'enum' and value not in prop.get('enum', []):")
lines.append("        return f'invalid_enum:{key}'")
lines.append("    if isinstance(value, str):")
lines.append("        if len(value) < prop.get('minLength', 0): return f'below_min:{key}'")
lines.append("        if len(value) > prop.get('maxLength', 10**9): return f'above_max:{key}'")
lines.append("        import re as _re")
lines.append("        p = prop.get('pattern')")
lines.append("        if p and not _re.search(p, value): return f'pattern_mismatch:{key}'")
lines.append("    return None")
lines.append("")
lines.append("")
lines.append("def generic_validate_arguments(tool_id: str, arguments: Any) -> list[str]:")
lines.append("    \"\"\"Validate WRITE arguments against the frozen tool contract schema.\"\"\"")
lines.append("    if tool_id not in WRITE_CONTRACTS:")
lines.append("        return ['unknown_tool']")
lines.append("    if not isinstance(arguments, Mapping):")
lines.append("        return ['arguments_not_object']")
lines.append("    schema = WRITE_CONTRACTS[tool_id]['input_schema']")
lines.append("    props = schema.get('properties', {})")
lines.append("    required = schema.get('required', [])")
lines.append("    violations: list[str] = []")
lines.append("    for key in sorted(arguments):")
lines.append("        if key not in props:")
lines.append("            violations.append(f'unknown_argument:{key}')")
lines.append("    for name in required:")
lines.append("        if name not in arguments:")
lines.append("            violations.append(f'missing_required:{name}')")
lines.append("    for name, value in arguments.items():")
lines.append("        if name not in props: continue")
lines.append("        err = _check_primitive(name, value, props[name])")
lines.append("        if err: violations.append(err)")
lines.append("    return violations")
lines.append("")
lines.append("")
lines.append("WRITE_TOOL_IDS: tuple[str, ...] = tuple(sorted(WRITE_CONTRACTS))")
lines.append("")

OUT.write_text("\n".join(lines))
print("wrote", OUT)
